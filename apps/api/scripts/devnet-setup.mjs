#!/usr/bin/env node
// Creates the "USDG (devnet)" test mint and the treasury token account on Solana devnet.
// Usage: pnpm --filter @socially/api build && node apps/api/scripts/devnet-setup.mjs [secrets-file]
// Secrets go only to the secrets file (default: <repo>/.env.devnet.local, gitignored, mode 0600).
// A rerun with an existing secrets file resumes with its keys.
// The script prints only public values.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { fileURLToPath } from "node:url";
import {
  appendTransactionMessageInstructions, createKeyPairSignerFromBytes, createKeyPairSignerFromPrivateKeyBytes, createSolanaRpc,
  createTransactionMessage, getAddressEncoder, getBase64EncodedWireTransaction, getSignatureFromTransaction,
  lamports, pipe, setTransactionMessageFeePayerSigner, setTransactionMessageLifetimeUsingBlockhash,
  signTransactionMessageWithSigners,
} from "@solana/kit";
import { getCreateAccountInstruction } from "@solana-program/system";
import {
  fetchMaybeMint, findAssociatedTokenPda, getCreateAssociatedTokenIdempotentInstruction, getInitializeMint2Instruction,
  getMintSize, getMintToCheckedInstruction, TOKEN_PROGRAM_ADDRESS,
} from "@solana-program/token";
import { assertDevnetGenesis, assertNotMainnetUrl, toRaw, TOKEN_DECIMALS, TOKEN_LABEL } from "../dist/token-chain.js";

const rpcUrl = process.env.DEVNET_RPC_URL ?? "https://api.devnet.solana.com";
const secretsFile = process.argv[2] ?? fileURLToPath(new URL("../../../.env.devnet.local", import.meta.url));
const treasuryFloat = toRaw(process.env.TREASURY_FLOAT ?? "1000000");

assertNotMainnetUrl(rpcUrl);
const rpc = createSolanaRpc(rpcUrl);
assertDevnetGenesis(await rpc.getGenesisHash().send());

async function newKeyPair() {
  const seed = randomBytes(32);
  const signer = await createKeyPairSignerFromPrivateKeyBytes(seed, true);
  const secret = [...seed, ...getAddressEncoder().encode(signer.address)];
  return { signer, secret: JSON.stringify(secret) };
}
const fromSecret = async (secret) => ({ signer: await createKeyPairSignerFromBytes(Uint8Array.from(JSON.parse(secret))), secret });

// A rerun resumes with the saved keys, so an interrupted setup never strands funded keys.
let mintKey, authority, treasury;
if (existsSync(secretsFile)) {
  const saved = Object.fromEntries(readFileSync(secretsFile, "utf8").split("\n")
    .filter((line) => /^[A-Z_]+=/.test(line)).map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1)]));
  mintKey = await fromSecret(saved.USDG_MINT_KEYPAIR);
  authority = await fromSecret(saved.MINT_AUTHORITY);
  treasury = await fromSecret(saved.TREASURY);
  console.log(`Resuming with the keys in ${secretsFile}`);
} else {
  mintKey = await newKeyPair();
  authority = await newKeyPair();
  treasury = await newKeyPair();
  // Persist the keys before any value depends on them.
  writeFileSync(secretsFile, [
    "# Devnet token layer secrets. Never commit. Generated by apps/api/scripts/devnet-setup.mjs",
    `DEVNET_RPC_URL=${rpcUrl}`,
    `USDG_MINT=${mintKey.signer.address}`,
    `MINT_AUTHORITY=${authority.secret}`,
    `TREASURY=${treasury.secret}`,
    "# The mint account key pair is not needed at runtime.",
    `USDG_MINT_KEYPAIR=${mintKey.secret}`,
    "",
  ].join("\n"), { mode: 0o600 });
}
const mint = mintKey.signer.address;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
async function waitFor(signature) {
  for (let i = 0; i < 90; i++) {
    const { value } = await rpc.getSignatureStatuses([signature], { searchTransactionHistory: true }).send();
    if (value[0]?.err) throw new Error(`Transaction ${signature} failed: ${JSON.stringify(value[0].err)}`);
    if (value[0]?.confirmationStatus === "confirmed" || value[0]?.confirmationStatus === "finalized") return;
    await sleep(1000);
  }
  throw new Error(`Transaction ${signature} was not confirmed in time`);
}

// The treasury pays every fee and rent in the token layer.
const funded = async () => (await rpc.getBalance(treasury.signer.address).send()).value >= 50_000_000n;
if (!(await funded())) {
  try {
    await waitFor(await rpc.requestAirdrop(treasury.signer.address, lamports(1_000_000_000n), { commitment: "confirmed" }).send());
  } catch (error) {
    console.warn(`Airdrop failed (${error.message}). Fund ${treasury.signer.address} at https://faucet.solana.com (devnet).`);
    while (!(await funded())) await sleep(5000);
  }
}

const [treasuryAta] = await findAssociatedTokenPda({ owner: treasury.signer.address, mint, tokenProgram: TOKEN_PROGRAM_ADDRESS });
if ((await fetchMaybeMint(rpc, mint)).exists) {
  console.log("Mint already exists; nothing to create.");
} else {
  const space = BigInt(getMintSize());
  const rent = await rpc.getMinimumBalanceForRentExemption(space).send();
  const { value: blockhash } = await rpc.getLatestBlockhash({ commitment: "confirmed" }).send();
  // One atomic transaction: the mint, the treasury token account and the treasury float.
  const message = pipe(
    createTransactionMessage({ version: 0 }),
    (m) => setTransactionMessageFeePayerSigner(treasury.signer, m),
    (m) => setTransactionMessageLifetimeUsingBlockhash(blockhash, m),
    (m) => appendTransactionMessageInstructions([
      getCreateAccountInstruction({ payer: treasury.signer, newAccount: mintKey.signer, lamports: rent, space, programAddress: TOKEN_PROGRAM_ADDRESS }),
      getInitializeMint2Instruction({ mint, decimals: TOKEN_DECIMALS, mintAuthority: authority.signer.address, freezeAuthority: null }),
      getCreateAssociatedTokenIdempotentInstruction({ payer: treasury.signer, ata: treasuryAta, owner: treasury.signer.address, mint }),
      getMintToCheckedInstruction({ mint, token: treasuryAta, mintAuthority: authority.signer, amount: treasuryFloat, decimals: TOKEN_DECIMALS }),
    ], m),
  );
  const signed = await signTransactionMessageWithSigners(message);
  const signature = getSignatureFromTransaction(signed);
  await rpc.sendTransaction(getBase64EncodedWireTransaction(signed), { encoding: "base64", preflightCommitment: "confirmed" }).send();
  await waitFor(signature);
  console.log(`Setup signature: ${signature}`);
}

console.log(`${TOKEN_LABEL} is ready.`);
console.log(`Secrets written to ${secretsFile}. Load them into the API environment.`);
console.log("Public config:");
console.log(`  DEVNET_RPC_URL=${rpcUrl}`);
console.log(`  USDG_MINT=${mint}`);
console.log(`  mint authority: ${authority.signer.address}`);
console.log(`  treasury owner: ${treasury.signer.address}`);
console.log(`  treasury token account: ${treasuryAta}`);
console.log(`  treasury float minted at creation: ${process.env.TREASURY_FLOAT ?? "1000000"} tokens`);
