import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../packages/contracts/src/markets.ts', import.meta.url), 'utf8');
const target = new URL('../../apk/src/api/generated/market-contracts.ts', import.meta.url);
const output = '// Generated by backend/scripts/sync-market-contracts.mjs. Edit the shared source.\n' + source;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Market contracts have drifted');
} else await writeFile(target, output);
