import { readFile,writeFile } from 'node:fs/promises';
const source=await readFile(new URL('../packages/contracts/src/vaults.ts',import.meta.url),'utf8');
const target=new URL('../../apk/src/api/generated/vault-contracts.ts',import.meta.url);
const output='// Generated by backend/scripts/sync-vault-contracts.mjs; edit the shared contracts source.\n'+source;
if (process.argv.includes('--check')) {
  if (await readFile(target,'utf8')!==output) throw new Error('APK vault contracts have drifted; run backend/scripts/sync-vault-contracts.mjs');
} else await writeFile(target,output);
